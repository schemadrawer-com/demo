-- Release 4: the back office. Beside the pet clinic's tables, the database now holds what the
-- application leans on - a schema for billing and one for the audit trail, types, sequences,
-- views, functions, procedures, triggers, and the rules the data has to meet.

CREATE EXTENSION IF NOT EXISTS citext;
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE SCHEMA billing;
CREATE SCHEMA audit;

CREATE TYPE visit_status AS ENUM ('scheduled', 'completed', 'cancelled');
CREATE TYPE weekday AS ENUM ('monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday', 'sunday');
CREATE DOMAIN email_address AS citext CHECK (VALUE ~ '^[^@\s]+@[^@\s]+$');
CREATE TYPE postal_address AS (street TEXT, postal_code TEXT, city TEXT);

CREATE SEQUENCE billing.invoice_number_seq START WITH 1000 INCREMENT BY 1;
CREATE SEQUENCE audit.event_number_seq START WITH 1 INCREMENT BY 1;
-- Handed out by the application when a visit is booked.
CREATE SEQUENCE visit_number_seq START WITH 1 INCREMENT BY 1;

-- Owners: an e-mail address, a full name the database keeps up to date, when the row last changed.
ALTER TABLE owners ADD COLUMN email email_address;
ALTER TABLE owners ADD COLUMN full_name TEXT GENERATED ALWAYS AS (first_name || ' ' || last_name) STORED;
ALTER TABLE owners ADD COLUMN updated_at TIMESTAMPTZ NOT NULL DEFAULT now();
ALTER TABLE owners ADD CONSTRAINT uq_owners_email UNIQUE (email);
ALTER TABLE owners ADD CONSTRAINT uq_owners_telephone UNIQUE (telephone);

-- Vets: a licence, and the hours they work.
ALTER TABLE vets ADD COLUMN license_number TEXT;
ALTER TABLE vets ADD CONSTRAINT uq_vets_license_number UNIQUE (license_number);

CREATE TABLE vet_schedules (
  id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vet_id    INT NOT NULL,
  day       weekday NOT NULL,
  starts_at TIME NOT NULL,
  ends_at   TIME NOT NULL,
  -- Filled in by the application.
  minutes   INT NOT NULL,
  CONSTRAINT uq_vet_schedules_vet_id_day UNIQUE (vet_id, day),
  CONSTRAINT ck_vet_schedules_hours CHECK (ends_at > starts_at)
);

-- Pets: how heavy, and what a pet cannot be.
ALTER TABLE pets ADD COLUMN weight_kg NUMERIC(5, 2);
ALTER TABLE pets ADD CONSTRAINT ck_pets_weight_kg CHECK (weight_kg > 0);
ALTER TABLE pets ADD CONSTRAINT ck_pets_birth_date CHECK (birth_date > DATE '1990-01-01');

-- Visits: who saw the pet, how long, what it cost, and whether it took place.
ALTER TABLE visits ADD COLUMN vet_id INT REFERENCES vets (id);
ALTER TABLE visits ADD COLUMN status visit_status NOT NULL DEFAULT 'scheduled';
ALTER TABLE visits ADD COLUMN duration_minutes INT;
ALTER TABLE visits ADD COLUMN price NUMERIC(8, 2);
ALTER TABLE visits ADD CONSTRAINT ck_visits_duration_minutes CHECK (duration_minutes BETWEEN 5 AND 480);
CREATE INDEX idx_visits_vet_id ON visits (vet_id);
CREATE INDEX idx_visits_visit_date ON visits (visit_date);

-- Billing.
CREATE TABLE billing.invoices (
  id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number    INT NOT NULL DEFAULT nextval('billing.invoice_number_seq'),
  visit_id  INT NOT NULL REFERENCES visits (id),
  amount    NUMERIC(10, 2) NOT NULL,
  tax       NUMERIC(10, 2) NOT NULL DEFAULT 0,
  total     NUMERIC(10, 2) GENERATED ALWAYS AS (amount + tax) STORED,
  issued_on DATE NOT NULL DEFAULT CURRENT_DATE,
  paid      BOOLEAN NOT NULL DEFAULT FALSE,
  CONSTRAINT uq_invoices_number UNIQUE (number),
  CONSTRAINT ck_invoices_amount CHECK (amount >= 0)
);
CREATE INDEX idx_invoices_visit_id ON billing.invoices (visit_id);

-- The audit trail: every change to a pet or a visit, written by a trigger.
CREATE TABLE audit.events (
  id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  number      BIGINT NOT NULL DEFAULT nextval('audit.event_number_seq'),
  table_name  TEXT NOT NULL,
  row_id      INT NOT NULL,
  operation   TEXT NOT NULL,
  happened_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE FUNCTION audit.log_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO audit.events (table_name, row_id, operation)
    VALUES (TG_TABLE_NAME, CASE WHEN TG_OP = 'DELETE' THEN OLD.id ELSE NEW.id END, TG_OP);
    RETURN NULL;
END
$$;

CREATE FUNCTION touch_owner() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END
$$;

CREATE FUNCTION default_visit_price() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.price IS NULL THEN
        NEW.price := 50;
    END IF;
    RETURN NEW;
END
$$;

CREATE FUNCTION pet_age_in_years(birth_date DATE) RETURNS INT LANGUAGE SQL STABLE AS $$
    SELECT EXTRACT(YEAR FROM age(birth_date))::INT
$$;

CREATE FUNCTION visits_of(owner INT) RETURNS SETOF visits LANGUAGE SQL STABLE AS $$
    SELECT v.* FROM visits v JOIN pets p ON p.id = v.pet_id WHERE p.owner_id = owner
$$;

CREATE PROCEDURE archive_visits(before DATE) LANGUAGE plpgsql AS $$
BEGIN
    DELETE FROM visits WHERE visit_date < before AND status <> 'scheduled';
END
$$;

CREATE PROCEDURE billing.mark_paid(invoice_id INT) LANGUAGE SQL AS $$
    UPDATE billing.invoices SET paid = TRUE WHERE id = invoice_id
$$;

CREATE TRIGGER trg_pets_audit AFTER INSERT OR UPDATE OR DELETE ON pets
    FOR EACH ROW EXECUTE FUNCTION audit.log_change();
CREATE TRIGGER trg_visits_audit AFTER INSERT OR UPDATE ON visits
    FOR EACH ROW EXECUTE FUNCTION audit.log_change();
CREATE TRIGGER trg_visits_default_price BEFORE INSERT ON visits
    FOR EACH ROW EXECUTE FUNCTION default_visit_price();
CREATE TRIGGER trg_owners_touch BEFORE UPDATE ON owners
    FOR EACH ROW EXECUTE FUNCTION touch_owner();

CREATE VIEW v_owner_pets AS
    SELECT o.id AS owner_id, o.full_name, p.id AS pet_id, p.name AS pet_name, t.name AS pet_type
    FROM owners o
    JOIN pets p ON p.owner_id = o.id
    JOIN types t ON t.id = p.type_id;

CREATE VIEW v_vet_specialties AS
    SELECT v.id AS vet_id, v.first_name, v.last_name, string_agg(s.name, ', ' ORDER BY s.name) AS specialties
    FROM vets v
    LEFT JOIN vet_specialties vs ON vs.vet_id = v.id
    LEFT JOIN specialties s ON s.id = vs.specialty_id
    GROUP BY v.id;

CREATE VIEW v_upcoming_visits AS
    SELECT v.id, v.visit_date, p.name AS pet_name, v.description
    FROM visits v
    JOIN pets p ON p.id = v.pet_id
    WHERE v.status = 'scheduled';

CREATE MATERIALIZED VIEW mv_visits_per_vet AS
    SELECT vet_id, count(*) AS visits, sum(price) AS revenue
    FROM visits
    GROUP BY vet_id;

CREATE MATERIALIZED VIEW billing.mv_unpaid_invoices AS
    SELECT id, number, visit_id, amount, issued_on
    FROM billing.invoices
    WHERE NOT paid;
