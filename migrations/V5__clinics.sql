-- Vets work at a clinic, and a visit takes place at one. Nothing that exists changes: a table,
-- two columns with their foreign keys and indexes, a view and a function come in.

CREATE TABLE clinics (
  id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name      TEXT NOT NULL,
  city      TEXT,
  telephone TEXT
);
CREATE INDEX idx_clinics_city ON clinics (city);

ALTER TABLE vets ADD COLUMN clinic_id INT REFERENCES clinics (id);
CREATE INDEX idx_vets_clinic_id ON vets (clinic_id);

ALTER TABLE visits ADD COLUMN clinic_id INT REFERENCES clinics (id);
CREATE INDEX idx_visits_clinic_id ON visits (clinic_id);

CREATE VIEW v_clinic_vets AS
    SELECT c.name AS clinic, c.city, v.first_name, v.last_name
    FROM clinics c
    JOIN vets v ON v.clinic_id = c.id;

CREATE FUNCTION clinic_of(vet INT) RETURNS TEXT LANGUAGE SQL STABLE AS $$
    SELECT c.name FROM clinics c JOIN vets v ON v.clinic_id = c.id WHERE v.id = vet
$$;
